"""Settings model.

Precedence, lowest to highest: field defaults, the ``[settings]`` table in
``profile.toml``, a ``.env`` file, environment variables, then CLI flags.
Every field can be set from env as ``PROFILE_<FIELD>``; the Steam key also
accepts the plain ``STEAM_API_KEY`` used by the GitHub secret.
"""

from __future__ import annotations

import os
import tomllib
from dataclasses import MISSING, asdict, dataclass, field, fields
from pathlib import Path
from typing import Any

ENV_PREFIX = "PROFILE_"
SECRET_FIELDS = {"steam_api_key"}
ENV_ALIASES = {"steam_api_key": ("STEAM_API_KEY",)}


def _f(default: Any, help: str, **kw: Any) -> Any:
    if isinstance(default, list):
        return field(default_factory=lambda: list(default), metadata={"help": help, **kw})
    return field(default=default, metadata={"help": help, **kw})


@dataclass
class Settings:
    template: Path = _f(Path("template.md"), "Markdown template with {{ placeholders }}.")
    output: Path = _f(Path("README.md"), "Where the rendered profile is written.")
    stats_url: str = _f(
        "https://seanomahoney.com/stats.json", "Portfolio stats (hackathons, festivals, Untappd)."
    )
    steam_id: str = _f("76561198101964519", "SteamID64 whose recent games are shown.")
    steam_api_key: str = _f("", "Steam Web API key. Leave empty to skip Steam.")
    steam_games: int = _f(5, "How many recently played games to show.")
    steam_fetch: int = _f(10, "How many recent games to request before filtering.")
    steam_blocked_descriptors: list[int] = _f(
        [3], "Steam content descriptor ids to hide (3 = adult only sexual content)."
    )
    timeout: float = _f(20.0, "HTTP timeout in seconds per request.")
    retries: int = _f(2, "Retries for transient HTTP failures (5xx, 429, network).")
    offline: bool = _f(False, "Use bundled demo data instead of the network.")
    strict: bool = _f(False, "Exit non-zero if any source fails (instead of using the snapshot).")

    # loading

    @classmethod
    def load(
        cls,
        config: Path | None = Path("profile.toml"),
        env_file: Path | None = Path(".env"),
        environ: dict[str, str] | None = None,
        overrides: dict[str, Any] | None = None,
    ) -> Settings:
        values: dict[str, Any] = {}
        if config and config.is_file():
            with config.open("rb") as fh:
                values.update(tomllib.load(fh).get("settings", {}))
        env = dict(read_env_file(env_file)) if env_file else {}
        env.update(os.environ if environ is None else environ)
        for f in fields(cls):
            names = (ENV_PREFIX + f.name.upper(), *ENV_ALIASES.get(f.name, ()))
            for name in names:
                if env.get(name, "") != "":
                    values[f.name] = env[name]
                    break
        values.update({k: v for k, v in (overrides or {}).items() if v is not None})
        unknown = set(values) - {f.name for f in fields(cls)}
        if unknown:
            raise ValueError(f"Unknown setting(s): {', '.join(sorted(unknown))}")
        return cls(**{k: _coerce(cls, k, v) for k, v in values.items()})

    def public(self) -> dict[str, Any]:
        """Settings as plain values with secrets masked."""
        out = {k: (str(v) if isinstance(v, Path) else v) for k, v in asdict(self).items()}
        for name in SECRET_FIELDS:
            out[name] = "set" if out[name] else "not set"
        return out


def _coerce(cls: type[Settings], name: str, value: Any) -> Any:
    kind = {f.name: f for f in fields(cls)}[name]
    default = kind.default if kind.default is not MISSING else kind.default_factory()
    if isinstance(default, bool):
        if isinstance(value, bool):
            return value
        return str(value).strip().lower() in {"1", "true", "yes", "on"}
    if isinstance(default, Path):
        return Path(value)
    if isinstance(default, int):
        return int(value)
    if isinstance(default, float):
        return float(value)
    if isinstance(default, list):
        if isinstance(value, str):
            value = [v for v in value.replace(" ", "").split(",") if v]
        return [int(v) for v in value]
    return str(value)


def read_env_file(path: Path) -> dict[str, str]:
    """Minimal .env parser: KEY=value lines, # comments, optional quotes."""
    if not path.is_file():
        return {}
    out: dict[str, str] = {}
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.removeprefix("export ").partition("=")
        out[key.strip()] = value.strip().strip("'\"")
    return out


def env_example() -> str:
    """Render .env.example from the settings model so the two never drift."""
    lines = [
        "# Generated by `profile-gen settings --env-example`. Copy to .env to use locally.",
        "",
    ]
    for f in fields(Settings):
        default = f.default if f.default is not MISSING else f.default_factory()
        if isinstance(default, list):
            default = ",".join(str(v) for v in default)
        elif isinstance(default, bool):
            default = str(default).lower()
        lines.append(f"# {f.metadata['help']}")
        aliases = ENV_ALIASES.get(f.name)
        if aliases:
            lines.append(f"# Also read from: {', '.join(aliases)}")
        value = "" if f.name in SECRET_FIELDS else default
        lines.append(f"{ENV_PREFIX}{f.name.upper()}={value}")
        lines.append("")
    return "\n".join(lines)
